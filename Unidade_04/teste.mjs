import assert from 'node:assert/strict';
import fs from 'node:fs';
import {criarBusca,paginar} from './web/busca.mjs';
import {avaliar} from './web/avaliacao.mjs';
const base=JSON.parse(fs.readFileSync(new URL('./web/receitas.json',import.meta.url)));
assert.equal(base.length,620);
assert.equal(new Set(base.map(r=>r.url)).size,620);
assert.ok(base.every(r=>r.ingredientes.length && r.titulo && r.url.startsWith('https://www.tudogostoso.com.br/receita/')));
const busca=criarBusca(base);
const frango=busca('Tenho frango e batata, mas não tenho forno.');
assert.deepEqual(frango.pedido.termos,['frango','batata']);
assert.deepEqual(frango.pedido.filtro,['forno']);
assert.ok(frango.items.length>0 && frango.items.length<=3);
assert.equal(frango.items[0].r.titulo,'Frango com batata');
assert.ok(frango.items.every(x=>!x.r.sinais.includes('forno')));
assert.equal(busca('dragão intergaláctico').items.length,0);
assert.equal(busca('ovo sem leite').items.length,0);
assert.equal(busca('bolo sem liquidificador').items.some(x=>x.r.sinais.includes('liquidificador')),false);
assert.ok(busca('bolo fubá').items.every(x=>x.match.includes('fuba')));
const pressao=busca('Tenho frango, mas não tenho panela de pressão.');
assert.deepEqual(pressao.pedido.filtro,['panela de pressão']);
assert.equal(pressao.ref.filter(x=>x.r.sinais.includes('panela de pressão')).length,3);
assert.equal(pressao.items.length,3);
assert.ok(pressao.items.every(x=>!x.r.sinais.includes('panela de pressão')));
assert.ok(base.find(r=>r.url.includes('/173263-')).sinais.includes('panela de pressão'));
const varios=busca('Tenho frango, mas não tenho panela de pressão, forno ou frigideira.');
assert.deepEqual(varios.pedido.filtro,['panela de pressão','forno','frigideira']);
assert.ok(varios.items.length && varios.items.every(x=>varios.pedido.filtro.every(f=>!x.r.sinais.includes(f))));
const misto=busca('Tenho frango, mas não tenho forno nem termocirculador.');
assert.deepEqual(misto.pedido.filtro,['forno']);
assert.deepEqual(misto.pedido.outros,['termocirculador']);
assert.equal(misto.items.length,0);
assert.deepEqual(busca('bolo sem fritadeira elétrica').pedido.filtro,['air fryer']);
assert.deepEqual(busca('frango sem frigideiras fundas').pedido.filtro,['frigideira']);
console.table(avaliar(busca));
console.log('Testes passaram.');

const consultaPaginada='Tenho frango e batata, mas não tenho forno.';
const {items:ordenadas}=busca(consultaPaginada,{todas:true});
assert.ok(ordenadas.length>3);
const urls=[];
for(let i=0;i<Math.ceil(ordenadas.length/3);i++){
  const lote=paginar(ordenadas,i);
  assert.equal(lote.inicio,i*3);
  assert.equal(lote.total,ordenadas.length);
  assert.equal(lote.items.length,Math.min(3,ordenadas.length-i*3));
  assert.ok(lote.items.every(x=>x.r.preparo && !x.r.sinais.includes('forno')));
  urls.push(...lote.items.map(x=>x.r.url));
}
assert.equal(new Set(urls).size,ordenadas.length);
assert.deepEqual(paginar(ordenadas,0).items,busca(consultaPaginada).items);
assert.deepEqual(paginar(ordenadas,Math.ceil(ordenadas.length/3)).items,[]);
assert.deepEqual(paginar([1,2,3,4,5],1).items,[4,5]);
console.log('Paginação verificada em '+ordenadas.length+' resultados da base.');
